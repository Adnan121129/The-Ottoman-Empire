/** The capital (or seat of power) in a given year. */
export function capitalForYear(year: number): { placeId: string; label: string; note?: string } {
  if (year < 1326) return { placeId: 'sogut', label: 'Söğüt', note: 'Early seats (Söğüt, Yenişehir) are known mainly from tradition' };
  if (year < 1365) return { placeId: 'bursa', label: 'Bursa' };
  if (year < 1453) return { placeId: 'edirne', label: 'Edirne', note: 'Bursa remained a dynastic centre; the date Edirne became the main seat is debated' };
  if (year <= 1919) return { placeId: 'constantinople', label: 'Constantinople (Istanbul)' };
  if (year <= 1922) return { placeId: 'constantinople', label: 'Istanbul (under Allied occupation) · Ankara (seat of the Grand National Assembly)' };
  return { placeId: 'ankara', label: 'Ankara (Republic of Turkey from 1923)', note: 'The Caliph remained in Istanbul until March 1924' };
}
